    [Fact]
    public async Task FullBookingJourney_HoldCheckoutWebhookConfirm_EndsWithConfirmedBookingAndTickets()
    {
        var (accessToken, _) = await RegisterConfirmedCustomerAndLoginAsync();
        using var client = CreateAuthenticatedClient(accessToken);
        var (showtimeId, seatIds, seatPrice) =
            await IntegrationTestDataSeeder.CreateScheduledShowtimeAsync(Factory.Services);
        var twoSeatIds = seatIds.Take(2).ToList();

        // 1. Hold two seats.
        var holdResponse = await client.PostAsJsonAsync(
            "/api/v1/bookings/hold",
            new
            {
                showtimeId,
                customerName = "Nguyen Van A",
                customerPhone = "0901234567",
                seatIds = twoSeatIds,
                combos = (object?)null,
            }
        );
        holdResponse.StatusCode.ShouldBe(HttpStatusCode.Created);
        var hold = await ReadDataAsync<HoldBookingResponseDto>(holdResponse);
        hold.Status.ShouldBe("Pending");
        hold.FinalAmount.ShouldBe(seatPrice * 2);

        // 2. Checkout via VNPay (fake gateway) — the real transactionId is generated by
        var checkoutResponse = await client.PostAsJsonAsync(
            $"/api/v1/bookings/{hold.BookingId}/checkout",
            new { paymentMethod = PaymentMethodNames.VnPay }
        );
        checkoutResponse.StatusCode.ShouldBe(HttpStatusCode.OK);
        var checkout = await ReadDataAsync<CheckoutResponseDto>(checkoutResponse);
        checkout.PaymentUrl.ShouldBe("https://fake-gateway.test/pay"); // FakePaymentGateway's default NextCreatePaymentResult
        var realTransactionId = Factory.VnPayGateway.CreatePaymentRequests.Last().TransactionId;

        // 3. Gateway calls our IPN webhook to confirm payment succeeded.
        Factory.VnPayGateway.NextCallbackResult = new(
            SignatureValid: true,
            IsSuccess: true,
            TransactionId: realTransactionId,
            GatewayResponseCode: "00",
            Amount: hold.FinalAmount,
            BookingId: hold.BookingId
        );
        var ipnResponse = await Client.GetAsync(
            $"/api/v1/payments/vnpay/ipn?vnp_TxnRef={realTransactionId}"
        );
        ipnResponse.StatusCode.ShouldBe(HttpStatusCode.OK);
        var ipnBody = await ReadEnvelopeAsync(ipnResponse);
        ipnBody.GetProperty("rspCode").GetString().ShouldBe("00");

        // 4. Booking must now be Confirmed with tickets generated and seats booked.
        var detailResponse = await client.GetAsync($"/api/v1/bookings/{hold.BookingId}");
        detailResponse.StatusCode.ShouldBe(HttpStatusCode.OK);
        var detail = await ReadEnvelopeAsync(detailResponse);
        detail.GetProperty("data").GetProperty("status").GetString().ShouldBe("Confirmed");
        detail.GetProperty("data").GetProperty("tickets").GetArrayLength().ShouldBe(2);
    }

    [Fact]
    public async Task HoldSeats_SameSeatRequestedByTwoCustomers_SecondRequestReturns409WithConflictSeatIds()
    {
        var (showtimeId, seatIds, _) = await IntegrationTestDataSeeder.CreateScheduledShowtimeAsync(
            Factory.Services
        );
        var contestedSeatId = seatIds[0];

        var (firstToken, _) = await RegisterConfirmedCustomerAndLoginAsync();
        using var firstClient = CreateAuthenticatedClient(firstToken);
        var (secondToken, _) = await RegisterConfirmedCustomerAndLoginAsync();
        using var secondClient = CreateAuthenticatedClient(secondToken);

        var firstHold = await firstClient.PostAsJsonAsync(
            "/api/v1/bookings/hold",
            new
            {
                showtimeId,
                customerName = "Khach 1",
                customerPhone = (string?)null,
                seatIds = new[] { contestedSeatId },
                combos = (object?)null,
            }
        );
        firstHold.StatusCode.ShouldBe(HttpStatusCode.Created);

        var secondHold = await secondClient.PostAsJsonAsync(
            "/api/v1/bookings/hold",
            new
            {
                showtimeId,
                customerName = "Khach 2",
                customerPhone = (string?)null,
                seatIds = new[] { contestedSeatId },
                combos = (object?)null,
            }
        );

        secondHold.StatusCode.ShouldBe(HttpStatusCode.Conflict);
        var body = await ReadEnvelopeAsync(secondHold);
        body.GetProperty("conflictSeatIds")
            .EnumerateArray()
            .Select(e => e.GetInt32())
            .ShouldContain(contestedSeatId);
    }

