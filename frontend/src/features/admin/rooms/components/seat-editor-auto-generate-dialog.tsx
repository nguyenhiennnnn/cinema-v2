import { useState } from "react";
import { Wand2 } from "lucide-react";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { resolveSeatVisualKind } from "@/components/common/seat-map/seat-map-types";
import type { SeatTypeDto } from "@/features/admin/catalog/types";
import type { AutoGenerateOptions } from "../hooks/use-seat-editor-state";

interface SeatEditorAutoGenerateDialogProps {
  rows: number;
  cols: number;
  seatTypes: SeatTypeDto[] | undefined;
  defaultSeatTypeId: number | null;
  onGenerate: (options: AutoGenerateOptions) => void;
}

export const SeatEditorAutoGenerateDialog = ({
  rows,
  cols,
  seatTypes,
  defaultSeatTypeId,
  onGenerate,
}: SeatEditorAutoGenerateDialogProps) => {
  const [open, setOpen] = useState(false);
  const [formRows, setFormRows] = useState(rows);
  const [formCols, setFormCols] = useState(cols);
  const [standardSeatTypeId, setStandardSeatTypeId] = useState<number | null>(defaultSeatTypeId);
  const [vipSeatTypeId, setVipSeatTypeId] = useState<number | null>(() => {
    const vip = seatTypes?.find((t) => resolveSeatVisualKind(t.name) === "vip");
    return vip?.seatTypeId ?? null;
  });
  const [vipRowCount, setVipRowCount] = useState(2);
  const [coupleRowCount, setCoupleRowCount] = useState(1);
  const [aisleColsText, setAisleColsText] = useState("");

  const parseAisleCols = (text: string) =>
    text
      .split(",")
      .map((s) => Number(s.trim()))
      .filter((n) => Number.isInteger(n) && n > 0);

  const handleSubmit = () => {
    const safeRows = Math.min(52, Math.max(1, formRows || 1));
    const safeCols = Math.min(60, Math.max(1, formCols || 1));
    onGenerate({
      rows: safeRows,
      cols: safeCols,
      standardSeatTypeId,
      vipSeatTypeId,
      vipRowCount: Math.max(0, Math.min(vipRowCount, safeRows)),
      coupleRowCount: Math.max(0, Math.min(coupleRowCount, safeRows)),
      aisleCols: parseAisleCols(aisleColsText).filter((c) => c <= safeCols),
    });
    setOpen(false);
  };

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger
        render={
          <Button type="button" variant="outline">
            <Wand2 className="size-4" />
            <span>Tạo layout tự động</span>
          </Button>
        }
      />
      <DialogContent className="sm:max-w-md">
        <DialogHeader>
          <DialogTitle>Tạo layout ghế tự động</DialogTitle>
          <DialogDescription>
            Nhập kích thước phòng, layout sẽ được tạo sẵn để bạn chỉnh tay tiếp. Thao tác này thay
            thế toàn bộ sơ đồ hiện tại (có thể bấm Hoàn tác nếu cần).
          </DialogDescription>
        </DialogHeader>

        <div className="flex flex-col gap-3">
          <div className="flex gap-3">
            <div className="flex flex-1 flex-col gap-1.5">
              <Label htmlFor="autogen-rows">Số hàng</Label>
              <Input
                id="autogen-rows"
                type="number"
                min={1}
                max={52}
                value={formRows}
                onChange={(e) => setFormRows(Number(e.target.value) || 1)}
              />
            </div>
            <div className="flex flex-1 flex-col gap-1.5">
              <Label htmlFor="autogen-cols">Số cột</Label>
              <Input
                id="autogen-cols"
                type="number"
                min={1}
                max={60}
                value={formCols}
                onChange={(e) => setFormCols(Number(e.target.value) || 1)}
              />
            </div>
          </div>

          <div className="flex flex-col gap-1.5">
            <Label htmlFor="autogen-standard-type">Loại ghế mặc định</Label>
            <select
              id="autogen-standard-type"
              value={standardSeatTypeId ?? ""}
              onChange={(e) => setStandardSeatTypeId(e.target.value ? Number(e.target.value) : null)}
              className="h-8 w-full border border-input bg-transparent px-2.5 text-sm outline-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
            >
              <option value="">— Không đặt —</option>
              {seatTypes?.map((t) => (
                <option key={t.seatTypeId} value={t.seatTypeId}>
                  {t.name}
                </option>
              ))}
            </select>
          </div>

          <div className="flex gap-3">
            <div className="flex flex-1 flex-col gap-1.5">
              <Label htmlFor="autogen-vip-type">Loại ghế VIP</Label>
              <select
                id="autogen-vip-type"
                value={vipSeatTypeId ?? ""}
                onChange={(e) => setVipSeatTypeId(e.target.value ? Number(e.target.value) : null)}
                className="h-8 w-full border border-input bg-transparent px-2.5 text-sm outline-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
              >
                <option value="">— Không có hàng VIP —</option>
                {seatTypes?.map((t) => (
                  <option key={t.seatTypeId} value={t.seatTypeId}>
                    {t.name}
                  </option>
                ))}
              </select>
            </div>
            <div className="flex w-28 flex-col gap-1.5">
              <Label htmlFor="autogen-vip-rows">Số hàng VIP</Label>
              <Input
                id="autogen-vip-rows"
                type="number"
                min={0}
                value={vipRowCount}
                onChange={(e) => setVipRowCount(Math.max(0, Number(e.target.value) || 0))}
              />
            </div>
          </div>
          <p className="text-xs text-muted-foreground">
            Hàng VIP được tính từ hàng cuối (gần màn hình nhất) trở lên trên.
          </p>

          <div className="flex flex-col gap-1.5">
            <Label htmlFor="autogen-couple-rows">Số hàng ghế đôi (tính từ hàng cuối cùng)</Label>
            <Input
              id="autogen-couple-rows"
              type="number"
              min={0}
              value={coupleRowCount}
              onChange={(e) => setCoupleRowCount(Math.max(0, Number(e.target.value) || 0))}
              className="w-28"
            />
          </div>

          <div className="flex flex-col gap-1.5">
            <Label htmlFor="autogen-aisles">Cột lối đi (số cột, cách nhau bởi dấu phẩy)</Label>
            <Input
              id="autogen-aisles"
              placeholder="VD: 4, 9"
              value={aisleColsText}
              onChange={(e) => setAisleColsText(e.target.value)}
            />
            <p className="text-xs text-muted-foreground">
              Các cột này sẽ để trống làm lối đi ở mọi hàng. Có thể bỏ trống.
            </p>
          </div>
        </div>

        <DialogFooter>
          <Button type="button" variant="outline" onClick={() => setOpen(false)}>
            Hủy
          </Button>
          <Button type="button" onClick={handleSubmit}>
            Tạo layout
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
};
