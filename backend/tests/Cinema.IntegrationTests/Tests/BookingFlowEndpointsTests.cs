    [Fact]
    public async Task HoldSeat_HighConcurrencyParallelRequests_OnlyOneWinsAndOthersGet409()
    {
        var (showtimeId, seatIds, _) = await IntegrationTestDataSeeder.CreateScheduledShowtimeAsync(
            Factory.Services
        );
        var targetSeatId = seatIds[0];
        const int concurrentUsersCount = 10;

        var clients = new List<HttpClient>();
        for (var i = 0; i < concurrentUsersCount; i++)
        {
            var (token, _) = await RegisterConfirmedCustomerAndLoginAsync();
            clients.Add(CreateAuthenticatedClient(token));
        }

        try
        {
            var barrier = new TaskCompletionSource(
                TaskCreationOptions.RunContinuationsAsynchronously
            );

            var tasks = clients
                .Select(
                    async (client, index) =>
                    {
                        await barrier.Task;
                        return await client.PostAsJsonAsync(
                            "/api/v1/bookings/hold",
                            new
                            {
                                showtimeId,
                                customerName = $"Concurrent Customer {index}",
                                customerPhone = (string?)null,
                                seatIds = new[] { targetSeatId },
                                combos = (object?)null,
                            }
                        );
                    }
                )
                .ToList();

            barrier.SetResult();
            var responses = await Task.WhenAll(tasks);

            var successResponses = responses
                .Where(r => r.StatusCode == HttpStatusCode.Created)
                .ToList();
            var conflictResponses = responses
                .Where(r => r.StatusCode == HttpStatusCode.Conflict)
                .ToList();

            successResponses.Count.ShouldBe(1);

            conflictResponses.Count.ShouldBe(concurrentUsersCount - 1);

            foreach (var conflictResponse in conflictResponses)
            {
                var body = await ReadEnvelopeAsync(conflictResponse);
                body.GetProperty("conflictSeatIds")
                    .EnumerateArray()
                    .Select(e => e.GetInt32())
                    .ShouldContain(targetSeatId);
            }
        }
        finally
        {
            foreach (var client in clients)
            {
                client.Dispose();
            }
        }
    }
