import { useState } from "react";
import { seatCellKey } from "@/components/common/seat-map/seat-map-types";
import type { SeatDto, UpdateSeatLayoutRequest } from "../types";
import type {
  AutoGenerateOptions,
  CopiedRow,
  EditorCell,
  EditorCellMap,
  SeatEditorBrush,
  ValidationIssue,
} from "../types/seat-editor";
import {
  applyBrushToCell,
  buildAutoGeneratedCells,
  buildInitialCells,
  buildSeatLayoutPayload,
  canPairSeats,
  pairCouple,
  pasteRowCells,
  resizeCells,
  unpairCouple,
} from "../utils/seat-editor-cells";
import { validateSeatLayout } from "../utils/seat-editor-validation";
import { useSeatEditorHistory } from "./use-seat-editor-history";

interface UseSeatEditorStateParams {
  initialRows: number;
  initialCols: number;
  initialSeats: SeatDto[] | undefined;
  defaultSeatTypeId: number | null;
}

export function useSeatEditorState({
  initialRows,
  initialCols,
  initialSeats,
  defaultSeatTypeId,
}: UseSeatEditorStateParams) {
  const history = useSeatEditorHistory(() => ({
    rows: initialRows,
    cols: initialCols,
    cells: buildInitialCells(initialRows, initialCols, initialSeats, defaultSeatTypeId),
  }));
  const { rows, cols, cells } = history.present;

  const [pendingCoupleKey, setPendingCoupleKey] = useState<string | null>(null);
  const [selectedKeys, setSelectedKeys] = useState<Set<string>>(new Set());
  const [copiedRow, setCopiedRow] = useState<CopiedRow | null>(null);

  const clearSelection = () => setSelectedKeys(new Set());
  const setSelectionKeys = (keys: string[]) => setSelectedKeys(new Set(keys));
  const selectAll = () => setSelectedKeys(new Set(cells.keys()));
  const toggleKeys = (keys: string[]) =>
    setSelectedKeys((prev) => {
      const allSelected = keys.length > 0 && keys.every((k) => prev.has(k));
      const next = new Set(prev);
      keys.forEach((k) => (allSelected ? next.delete(k) : next.add(k)));
      return next;
    });
  const selectRow = (rowLabel: string) =>
    toggleKeys(
      Array.from(cells.values())
        .filter((c) => c.seatRow === rowLabel)
        .map((c) => seatCellKey(c.seatRow, c.seatNumber)),
    );
  const selectCol = (col: number) =>
    toggleKeys(
      Array.from(cells.values())
        .filter((c) => c.seatNumber === col)
        .map((c) => seatCellKey(c.seatRow, c.seatNumber)),
    );
  const resetTransientState = () => {
    setPendingCoupleKey(null);
    clearSelection();
  };

  const commitCells = (next: EditorCellMap) => history.commit({ rows, cols, cells: next });

  const undo = () => {
    if (history.undo()) resetTransientState();
  };

  const redo = () => {
    if (history.redo()) resetTransientState();
  };

  const resize = (newRows: number, newCols: number) => {
    history.commit({
      rows: newRows,
      cols: newCols,
      cells: resizeCells(cells, newRows, newCols, defaultSeatTypeId),
    });
    resetTransientState();
  };

  const applyPairCouple = (key: string, cell: EditorCell): string | null => {
    if (cell.isAisle) return "Không thể ghép ghế đôi tại ô lối đi.";

    if (cell.coupleId) {
      commitCells(unpairCouple(cells, cell.coupleId));
      setPendingCoupleKey(null);
      return null;
    }

    if (!pendingCoupleKey) {
      setPendingCoupleKey(key);
      return null;
    }

    if (pendingCoupleKey === key) {
      setPendingCoupleKey(null);
      return null;
    }

    const pendingCell = cells.get(pendingCoupleKey);
    if (!canPairSeats(pendingCell, cell)) {
      setPendingCoupleKey(key);
      return "Chỉ ghép được 2 ghế liền kề trong cùng một hàng.";
    }

    commitCells(pairCouple(cells, pendingCoupleKey, pendingCell, key, cell));
    setPendingCoupleKey(null);
    return null;
  };

  const applyBrush = (rowLabel: string, col: number, brush: SeatEditorBrush): string | null => {
    const key = seatCellKey(rowLabel, col);
    const cell = cells.get(key);
    if (!cell) return null;

    if (brush.type === "pairCouple") return applyPairCouple(key, cell);

    const next = new Map(cells);
    next.set(key, applyBrushToCell(cell, brush));
    commitCells(next);
    return null;
  };

  const applyBrushToSelection = (brush: SeatEditorBrush): string | null => {
    if (selectedKeys.size === 0) return "Chưa chọn ô ghế nào để áp dụng.";
    if (brush.type === "pairCouple") {
      return "Không thể ghép ghế đôi hàng loạt — hãy chọn từng cặp ghế bằng công cụ ghép ghế đôi.";
    }
    const solidBrush: Exclude<SeatEditorBrush, { type: "pairCouple" }> = brush;

    const selected = Array.from(selectedKeys)
      .map((key) => ({ key, cell: cells.get(key) }))
      .filter((entry): entry is { key: string; cell: EditorCell } => !!entry.cell);

    const next = new Map(cells);
    if (solidBrush.type === "toggleActive") {
      const targetActive = !selected.some(({ cell }) => cell.isActive && !cell.isAisle);
      selected.forEach(({ key, cell }) => {
        if (!cell.isAisle) next.set(key, { ...cell, isActive: targetActive });
      });
    } else if (solidBrush.type === "toggleAisle") {
      const targetAisle = selected.some(({ cell }) => !cell.isAisle);
      selected.forEach(({ key, cell }) => {
        if (cell.isAisle !== targetAisle) next.set(key, applyBrushToCell(cell, solidBrush));
      });
    } else {
      selected.forEach(({ key, cell }) => next.set(key, applyBrushToCell(cell, solidBrush)));
    }
    commitCells(next);
    clearSelection();
    return null;
  };

  const disableSelection = () => {
    if (selectedKeys.size === 0) return;
    const next = new Map(cells);
    selectedKeys.forEach((key) => {
      const cell = next.get(key);
      if (cell && !cell.isAisle) next.set(key, { ...cell, isActive: false });
    });
    commitCells(next);
    clearSelection();
  };

  const copyRow = (rowLabel: string) => {
    const rowCells = Array.from(cells.values())
      .filter((c) => c.seatRow === rowLabel)
      .sort((a, b) => a.seatNumber - b.seatNumber);
    if (rowCells.length > 0) setCopiedRow({ sourceRow: rowLabel, cells: rowCells });
  };

  const pasteRow = (targetRowLabel: string): string | null => {
    if (!copiedRow) return "Chưa sao chép hàng ghế nào.";
    if (targetRowLabel === copiedRow.sourceRow) {
      return "Không thể dán vào chính hàng ghế đã sao chép.";
    }
    commitCells(pasteRowCells(cells, copiedRow, targetRowLabel));
    return null;
  };

  const autoGenerate = (options: AutoGenerateOptions) => {
    history.commit({
      rows: options.rows,
      cols: options.cols,
      cells: buildAutoGeneratedCells(options),
    });
    resetTransientState();
    setCopiedRow(null);
  };

  const cellList = Array.from(cells.values());

  const validate = (): ValidationIssue[] => validateSeatLayout(cellList, rows, cols);

  const buildPayload = (): UpdateSeatLayoutRequest => buildSeatLayoutPayload(rows, cols, cellList);

  return {
    rows,
    cols,
    cellMap: cells,
    cellList,
    pendingCoupleKey,
    isDirty: history.isDirty,
    resize,
    applyBrush,
    buildPayload,
    markSaved: history.markSaved,

    canUndo: history.canUndo,
    canRedo: history.canRedo,
    undo,
    redo,

    selectedKeys,
    setSelectionKeys,
    clearSelection,
    selectAll,
    selectRow,
    selectCol,
    applyBrushToSelection,
    disableSelection,

    copiedRow,
    copyRow,
    cancelCopyRow: () => setCopiedRow(null),
    pasteRow,

    validate,
    autoGenerate,
  };
}
